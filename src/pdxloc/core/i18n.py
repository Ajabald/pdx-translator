"""Перевод строк приложения — единственная точка, через которую он идёт.

Строки в коде написаны по-английски: `pyside6-lupdate` привязывает перевод к
тексту оригинала, поэтому оригинал обязан быть тем языком, с которого будут
переводить остальные. Русский поэтому такой же перевод, как китайский, и живёт
в `gui/translations/pdxloc_ru.ts`.

**Ядру нельзя зависеть от Qt.** Режим `--scan-cli` работает без PySide6, и
проверки качества гоняются в тестах без окна. Поэтому модуль деградирует до
тождественной функции, когда Qt нет, — тем же приёмом, что `settings._get`.

Два способа пометить строку, и путать их нельзя:

* `QT_TRANSLATE_NOOP("Контекст", "Text")` — **для таблиц уровня модуля**
  (`actions.ACTIONS`, `qa_rules.BUILTIN_RULES`, `statuses.STATUS_LABELS`). Они
  вычисляются на импорте, когда переводчик ещё не установлен: перевести там
  значит навсегда запомнить непереведённое. Возвращает строку как есть, а
  переводится она в момент показа;
* `translate("Контекст", "Text")` — **в момент показа**.

Имя `translate` выбрано не случайно: lupdate узнаёт вызов по имени. Функция с
именем `tr` была бы разобрана как метод QObject с сигнатурой
(текст, уточнение) — и второй аргумент уехал бы в комментарий вместо контекста.
`QT_TRANSLATE_NOOP` по той же причине реэкспортируется под своим именем:
`from ... import QT_TRANSLATE_NOOP as NOOP` делает строку невидимой для сборщика.
"""
from __future__ import annotations

try:
    from PySide6.QtCore import QCoreApplication
    from PySide6.QtCore import QT_TRANSLATE_NOOP        # noqa: F401 — реэкспорт
except ImportError:                                     # без Qt: --scan-cli, тесты ядра
    QCoreApplication = None

    def QT_TRANSLATE_NOOP(context: str, text: str) -> str:      # noqa: N802
        return text


def translate(context: str, text: str, disambiguation: str | None = None,
              n: int = -1) -> str:
    """Перевод строки в момент показа.

    Без Qt (и до установки переводчика) возвращает оригинал — это и есть
    английский интерфейс, а не заглушка.

    Больше аргументов у вызова быть не должно: lupdate разбирает его по форме
    и на незнакомом (в том числе именованном) аргументе **молча теряет строку**
    целиком. Подстановка значений поэтому вынесена в `fill`.
    """
    if QCoreApplication is None:
        return text
    return QCoreApplication.translate(context, text, disambiguation, n)


def fill(template: str, *values) -> str:
    """Подставить значения в `%1`, `%2`… уже переведённого шаблона.

    Заведено отдельной функцией, а не аргументом `translate`, по прозаичной
    причине выше. Форма `%N` — соглашение Qt: Linguist показывает такие
    подстановки переводчику отдельно и ругается, если тот их потерял. Клеить
    строку из кусков нельзя вовсе: порядок слов в языках разный, и переводчик
    получил бы обрывки без всякой возможности их переставить.
    """
    text = template
    for index, value in enumerate(values, start=1):
        text = text.replace(f"%{index}", str(value))
    return text
